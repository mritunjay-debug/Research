import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url),core=require('../pillar-load-core.js');
const near=(a,b,t=1e-9)=>assert.ok(Math.abs(a-b)<=t,`expected ${a} ≈ ${b}`);
near(core.verticalStress(.028,80),2.24);
near(core.tributaryPillarStress(2.24,16,18,10,12),5.376);
assert.equal(core.verticalStress(.028,-1),null);
assert.equal(core.verticalStress(-.028,80),null);
assert.equal(core.tributaryPillarStress(2,0,10,10,10),null);
assert.equal(core.estimateStrength(70,10,3,'stress'),null);
assert.equal(core.estimateStrength(70,10,0,'krauland'),null);
near(core.estimateStrength(70,10,3,'krauland'),.354*70*(.778+.222*(10/3)));
assert.equal(core.estimateStrength(70,.5,3,'lunder'),null);
assert.ok(core.estimateStrength(70,10,3,'lunder')>0);
const row=core.calculateRow({id:'P1',width_x_m:10,length_y_m:12,height_m:3,ucs_mpa:70,tributary_width_m:16,tributary_length_m:18,depth_m:80,unit_weight_mn_m3:.028,method:'krauland'});
assert.equal(row.valid,true);near(row.vertical_stress_mpa,2.24);near(row.pillar_stress_mpa,5.376);near(row.strength_stress_ratio,row.estimated_strength_mpa/5.376);
const bad=core.calculateRow({id:'',width_x_m:10,length_y_m:10,height_m:3,ucs_mpa:70,tributary_width_m:null,tributary_length_m:null,depth_m:-1,unit_weight_mn_m3:.028,method:'lunder'});
assert.equal(bad.valid,false);assert.ok(bad.errors.length>=3);
console.log('Pillar load core tests passed: stress units, tributary area, empirical model domain, and invalid-input handling.');
